-- 1. DDL - Estrutura do Banco de Dados
-- ================================================

-- 1.1 Clientes (segurados)
CREATE TABLE CS_CLIENTES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RAZAO_SOCIAL VARCHAR2(150) NOT NULL,
    CNPJ VARCHAR2(20) UNIQUE NOT NULL,
    FIDELIDADE VARCHAR2(50)
);

-- 1.2 Fazendas (vinculadas aos clientes)
CREATE TABLE CS_FAZENDAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_FAZENDA VARCHAR2(100) NOT NULL,
    ID_CLIENTE NUMBER NOT NULL,
    CULTURA VARCHAR2(50),
    MUNICIPIO VARCHAR2(100),
    ESTADO VARCHAR2(2),
    LATITUDE NUMBER(10, 8),
    LONGITUDE NUMBER(11, 8),
    TAMANHO NUMBER(15, 2),
    CONSTRAINT FK_FAZENDAS_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CS_CLIENTES(ID)
);

-- 1.3 Dados Climáticos (telemetria - Open-Meteo)
CREATE TABLE CS_CLIMA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_FAZENDA NUMBER NOT NULL,
    TEMPERATURA NUMBER(5, 2),
    UMIDADE NUMBER(5, 2),
    VELOCIDADE_VENTO NUMBER(5, 2),
    DATA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_CLIMA_FAZENDA FOREIGN KEY (ID_FAZENDA) REFERENCES CS_FAZENDAS(ID)
);

-- 1.4 Alertas de Risco (populado pelo modelo de ML)
CREATE TABLE CS_ALARMES_CLIMA (
    ID_ALARME NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLIENTE NUMBER NOT NULL,
    ID_FAZENDA NUMBER NOT NULL,
    TEMPERATURA NUMBER(5, 2),
    UMIDADE NUMBER(5, 2),
    VELOCIDADE_VENTO NUMBER(5, 2),
    TIPO_ALARME VARCHAR2(50),
    DATA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ALARME_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CS_CLIENTES(ID),
    CONSTRAINT FK_ALARME_FAZENDA FOREIGN KEY (ID_FAZENDA) REFERENCES CS_FAZENDAS(ID)
);

-- 1.5 Eventos Climáticos Extremos (INPE/Cemaden)
CREATE TABLE CS_CLIMA_EVENTOS (
    ID_FAZENDA NUMBER,
    UF VARCHAR2(26),
    MUNICIPIO VARCHAR2(50),
    REGISTRO DATE,
    PROTOCOLO VARCHAR2(128),
    COBRADE VARCHAR2(300),
    STATUS VARCHAR2(26),
    DM_17 NUMBER, DM_18 NUMBER, DM_19 NUMBER, DM_20 NUMBER, DM_21 NUMBER, DM_22 NUMBER,
    PEPL_1 NUMBER, PEPL_2 NUMBER, PEPL_3 NUMBER, PEPL_4 NUMBER,
    PEPL_S5 NUMBER, PEPL_6 NUMBER, PEPL_7 NUMBER, PEPL_8 NUMBER,
    PEPL_9 NUMBER, PEPL_10 NUMBER, PEPL_11 NUMBER,
    PEPR_AGRICULTURA VARCHAR2(26),
    PEPR_13 NUMBER, PEPR_14 NUMBER, PEPR_15 NUMBER, PEPR_16 NUMBER
);


-- 2. Queries Analíticas de Risco
-- ================================================

-- 2.1 Score de Risco Atual por Fazenda (última leitura)
WITH ultima_leitura AS (
    SELECT ID_FAZENDA, TEMPERATURA, UMIDADE, VELOCIDADE_VENTO, DATA_HORA,
           ROW_NUMBER() OVER (PARTITION BY ID_FAZENDA ORDER BY DATA_HORA DESC) AS rn
    FROM CS_CLIMA
)
SELECT u.TEMPERATURA, u.UMIDADE, u.VELOCIDADE_VENTO, u.DATA_HORA,
       f.NOME_FAZENDA, f.ESTADO, f.MUNICIPIO, f.CULTURA,
       c.RAZAO_SOCIAL, c.FIDELIDADE
FROM ultima_leitura u
JOIN CS_FAZENDAS f ON u.ID_FAZENDA = f.ID
JOIN CS_CLIENTES c ON f.ID_CLIENTE = c.ID
WHERE u.rn = 1
ORDER BY f.NOME_FAZENDA;

-- 2.2 Média Histórica por Estado (análise de correlação)
SELECT f.ESTADO,
       ROUND(AVG(c.TEMPERATURA), 2) AS MEDIA_TEMP,
       ROUND(AVG(c.UMIDADE), 2) AS MEDIA_UMIDADE,
       ROUND(AVG(c.VELOCIDADE_VENTO), 2) AS MEDIA_VENTO,
       ROUND(STDDEV(c.TEMPERATURA), 2) AS DESVIO_TEMP,
       COUNT(*) AS TOTAL_LEITURAS
FROM CS_CLIMA c
JOIN CS_FAZENDAS f ON c.ID_FAZENDA = f.ID
GROUP BY f.ESTADO
ORDER BY MEDIA_TEMP DESC;

-- 2.3 Dias Críticos por Fazenda (alta temperatura + baixa umidade)
SELECT f.NOME_FAZENDA, f.ESTADO,
       TRUNC(c.DATA_HORA) AS DATA,
       MAX(c.TEMPERATURA) AS MAX_TEMP,
       MIN(c.UMIDADE) AS MIN_UMIDADE,
       MAX(c.VELOCIDADE_VENTO) AS MAX_VENTO
FROM CS_CLIMA c
JOIN CS_FAZENDAS f ON c.ID_FAZENDA = f.ID
WHERE c.TEMPERATURA > 35 OR c.UMIDADE < 20
GROUP BY f.NOME_FAZENDA, f.ESTADO, TRUNC(c.DATA_HORA)
HAVING MAX(c.TEMPERATURA) > 35
ORDER BY MAX_TEMP DESC;

-- 2.4 Alertas Emitidos vs Condições (quando CS_ALARMES_CLIMA tiver dados)
SELECT a.ID_ALARME, a.TIPO_ALARME, a.DATA_HORA,
       f.NOME_FAZENDA, f.ESTADO,
       a.TEMPERATURA, a.UMIDADE, a.VELOCIDADE_VENTO,
       c.RAZAO_SOCIAL
FROM CS_ALARMES_CLIMA a
JOIN CS_FAZENDAS f ON a.ID_FAZENDA = f.ID
JOIN CS_CLIENTES c ON a.ID_CLIENTE = c.ID
ORDER BY a.DATA_HORA DESC;

-- 2.5 Correlação entre Variáveis Climáticas e Incidentes
SELECT CORR(c.MEDIA_TEMP, c.QTD_INCIDENTES) AS CORR_TEMP_INCIDENTE,
       CORR(c.MEDIA_UMIDADE, c.QTD_INCIDENTES) AS CORR_UMIDADE_INCIDENTE,
       CORR(c.MEDIA_VENTO, c.QTD_INCIDENTES) AS CORR_VENTO_INCIDENTE
FROM (
    SELECT TRUNC(cl.DATA_HORA) AS DATA,
           AVG(cl.TEMPERATURA) AS MEDIA_TEMP,
           AVG(cl.UMIDADE) AS MEDIA_UMIDADE,
           AVG(cl.VELOCIDADE_VENTO) AS MEDIA_VENTO,
           COUNT(e.PROTOCOLO) AS QTD_INCIDENTES
    FROM CS_CLIMA cl
    LEFT JOIN CS_CLIMA_EVENTOS e
        ON cl.ID_FAZENDA = e.ID_FAZENDA
        AND TRUNC(cl.DATA_HORA) = TRUNC(e.REGISTRO)
    GROUP BY TRUNC(cl.DATA_HORA)
) c;

-- 2.6 Top 5 Fazendas com Maior Exposição a Eventos Climáticos
SELECT f.NOME_FAZENDA, f.ESTADO, f.MUNICIPIO,
       c.RAZAO_SOCIAL,
       COUNT(e.PROTOCOLO) AS TOTAL_EVENTOS,
       COUNT(DISTINCT e.COBRADE) AS TIPOS_EVENTO
FROM CS_CLIMA_EVENTOS e
JOIN CS_FAZENDAS f ON e.ID_FAZENDA = f.ID
JOIN CS_CLIENTES c ON f.ID_CLIENTE = c.ID
GROUP BY f.NOME_FAZENDA, f.ESTADO, f.MUNICIPIO, c.RAZAO_SOCIAL
ORDER BY TOTAL_EVENTOS DESC
    FETCH FIRST 5 ROWS ONLY;

