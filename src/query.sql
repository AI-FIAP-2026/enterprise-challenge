-- 3.1 Eventos Climáticos Agregados por UF + Município (US-001 - Score Risk)
-- Soma todos os danos materiais (DM_*) + perdas econômicas (PEPL_*) + perdas (PEPR_*)
-- para obter o impacto econômico total por evento.
SELECT UF, MUNICIPIO, COBRADE, REGISTRO, PEPR_AGRICULTURA,
       NVL(DM_17,0)+NVL(DM_18,0)+NVL(DM_19,0)+NVL(DM_20,0)+
       NVL(DM_21,0)+NVL(DM_22,0)+
       NVL(PEPL_1,0)+NVL(PEPL_2,0)+NVL(PEPL_3,0)+NVL(PEPL_4,0)+
       NVL(PEPL_S5,0)+NVL(PEPL_6,0)+NVL(PEPL_7,0)+NVL(PEPL_8,0)+
       NVL(PEPL_9,0)+NVL(PEPL_10,0)+NVL(PEPL_11,0)+
       NVL(PEPR_13,0)+NVL(PEPR_14,0)+NVL(PEPR_15,0)+NVL(PEPR_16,0)
       AS IMPACTO_TOTAL
FROM CS_CLIMA_EVENTOS
ORDER BY UF, MUNICIPIO, REGISTRO;

-- 3.2 Score Risk por Município (US-001)
-- Calcula frequência e impacto total agregado por município.
SELECT UF, MUNICIPIO,
       COUNT(*) AS TOTAL_EVENTOS,
       SUM(NVL(DM_17,0)+NVL(DM_18,0)+NVL(DM_19,0)+NVL(DM_20,0)+
           NVL(DM_21,0)+NVL(DM_22,0)+
           NVL(PEPL_1,0)+NVL(PEPL_2,0)+NVL(PEPL_3,0)+NVL(PEPL_4,0)+
           NVL(PEPL_S5,0)+NVL(PEPL_6,0)+NVL(PEPL_7,0)+NVL(PEPL_8,0)+
           NVL(PEPL_9,0)+NVL(PEPL_10,0)+NVL(PEPL_11,0)+
           NVL(PEPR_13,0)+NVL(PEPR_14,0)+NVL(PEPR_15,0)+NVL(PEPR_16,0))
       AS IMPACTO_TOTAL
FROM CS_CLIMA_EVENTOS
GROUP BY UF, MUNICIPIO
ORDER BY UF, MUNICIPIO;

-- 3.3 Classificação de Alertas (US-002)
-- Identifica registros de clima que disparam alertas conforme as regras de negócio.
SELECT c.ID_FAZENDA, f.NOME_FAZENDA, c.RAZAO_SOCIAL,
       c.TEMPERATURA, c.UMIDADE, c.VELOCIDADE_VENTO, c.DATA_HORA,
       CASE
           WHEN c.TEMPERATURA > 30 AND c.UMIDADE < 30 AND c.VELOCIDADE_VENTO > 30
               THEN 'Incêndio Crítico'
           WHEN c.UMIDADE < 12 THEN 'Incêndio Alto - Umidade Crítica'
           WHEN c.TEMPERATURA > 40 THEN 'Incêndio Alto - Temperatura Extrema'
           WHEN c.TEMPERATURA < 5 OR c.TEMPERATURA > 30 THEN 'Operacional Alto - Temperatura'
           WHEN c.VELOCIDADE_VENTO > 75 THEN 'Operacional Crítico - Ventania'
           WHEN c.VELOCIDADE_VENTO > 60 THEN 'Operacional Alto - Ventania'
           ELSE NULL
       END AS TIPO_ALARME
FROM CS_CLIMA c
JOIN CS_FAZENDAS f ON c.ID_FAZENDA = f.ID
JOIN CS_CLIENTES c ON f.ID_CLIENTE = c.ID
WHERE (c.TEMPERATURA > 30 AND c.UMIDADE < 30 AND c.VELOCIDADE_VENTO > 30)
   OR c.UMIDADE < 12
   OR c.TEMPERATURA > 40
   OR c.TEMPERATURA < 5
   OR c.VELOCIDADE_VENTO > 60
ORDER BY c.DATA_HORA DESC;
